    """Higher timeframe trend analysis."""
    
    trend_4h: int = 0  # -1, 0, +1
    trend_1d: int = 0  # -1, 0, +1
    combined_score: int = 0  # -2 to +2
    
    @property
    def is_bullish(self) -> bool:
        return self.combined_score > 0
    
    @property
    def is_bearish(self) -> bool:
        return self.combined_score < 0
    
    @property
    def is_neutral(self) -> bool:
        return self.combined_score == 0


