class Position(BaseModel):
    """
    Active trading position.
    
    Tracks all aspects of an open position including partial closes,
    breakeven state, and trailing stop.
    """
    
    position_id: str
    exchange: str
    symbol: str
    side: PositionSide
    strategy: str
    
    # Size & Entry
    initial_quantity: float
    remaining_quantity: float
    entry_price: float
    actual_entry_price: float  # After fees/slippage
    
    # Exit levels
    stop_loss: float
    tp1: float
    tp2: float
    tp3: float
    
    # TP tracking
    tp1_hit: bool = False
    tp2_hit: bool = False
    tp3_hit: bool = False
    tp1_closed_qty: float = 0.0
    tp2_closed_qty: float = 0.0
    tp3_closed_qty: float = 0.0
    
    # Risk management
    initial_risk: float  # In price units
    risk_pct: float
    breakeven_active: bool = False
    trailing_active: bool = False
    trailing_stop_price: Optional[float] = None
    
    # State
    regime: MarketRegime
    opened_at: datetime
    closed_at: Optional[datetime] = None
    closed_reason: Optional[str] = None
    
    # PnL
    realized_pnl: float = 0.0
    unrealized_pnl: float = 0.0
    fees_paid: float = 0.0
    
    # References
    signal_id: str
    entry_order_id: Optional[str] = None
    
    class Config:
        json_encoders = {
            datetime: lambda v: v.isoformat()
        }
    
    @property
    def is_closed(self) -> bool:
        return self.remaining_quantity <= 0
    
    @property
    def is_long(self) -> bool:
        return self.side == PositionSide.LONG
    
    @property
    def is_short(self) -> bool:
        return self.side == PositionSide.SHORT
    
    def get_current_pnl(self, current_price: float) -> float:
        """Calculate current PnL based on price."""
        if self.is_long:
            return (current_price - self.entry_price) * self.remaining_quantity
        else:
            return (self.entry_price - current_price) * self.remaining_quantity
    
    def get_pnl_percentage(self, current_price: float) -> float:
        """Calculate PnL as percentage of entry."""
        if self.is_long:
            return ((current_price - self.entry_price) / self.entry_price) * 100
        else:
            return ((self.entry_price - current_price) / self.entry_price) * 100
    
    def get_r_multiple(self, current_price: float) -> float:
        """Calculate R multiple (profit/loss relative to initial risk)."""
        pnl = self.get_current_pnl(current_price)
        if self.initial_risk == 0:
            return 0
        return pnl / (self.initial_risk * self.initial_quantity)


