class StrategySignal(BaseModel):
    """
    Trading signal generated by strategy core.
    
    This is the primary output of the strategy engine.
    Contains all information needed for risk assessment and order execution.
    """
    
    signal_id: str
    timestamp: datetime
    exchange: str
    symbol: str
    timeframe: str
    
    action: SignalAction
    
    # Entry/Exit levels
    entry_price: float
    stop_loss: float
    tp1: float
    tp2: float
    tp3: float
    
    # Strategy context
    regime: MarketRegime
    votes: int  # 0-3
    votes_required: int
    htf_4h: int  # -1, 0, +1
    htf_1d: int  # -1, 0, +1
    adx: float
    atr: float
    volume_ratio: float
    
    # Structure
    bos_detected: bool
    choch_detected: bool
    swing_level: float  # Entry reference
    
    # Risk
    risk_pct: float
    position_size: float
    risk_amount: float
    reward_ratio: float
    
    # Filters
    impulse_ok: bool
    atr_ok: bool
    bos_ok: bool
    cooldown_ok: bool
    range_conditions_ok: bool
    
    # Metadata
    strategy_version: str = "SMT_PRO_V2"
    confirmation_type: str = "BODY"  # BODY or WICK
    
    class Config:
        json_encoders = {
            datetime: lambda v: v.isoformat()
        }
    
    @property
    def is_valid(self) -> bool:
        """Check if signal passes all filters."""
        return (
            self.action in [SignalAction.LONG, SignalAction.SHORT] and
            self.cooldown_ok and
            self.atr_ok and
            self.bos_ok and
            self.range_conditions_ok and
            self.votes >= self.votes_required
        )


