    """Current strategy settings."""
    __tablename__ = "strategy_settings"

    id = Column(Integer, primary_key=True, autoincrement=True)
    version = Column(Integer, default=1)
    structure_period = Column(Integer, default=20)
    confirmation_type = Column(String(10), default="Body")  # Body, Wick
    htf1 = Column(String(10), default="4h")
    htf2 = Column(String(10), default="1d")
    adx_th = Column(Integer, default=20)
    adx_trend = Column(Integer, default=25)
    adx_dead = Column(Integer, default=15)
    filter_mode = Column(String(10), default="2of3")  # 2of3, ALL
    vol_mult = Column(Float, default=1.5)
    use_impulse = Column(Boolean, default=True)
    impulse_mult = Column(Float, default=1.0)
    use_range_bounce = Column(Boolean, default=True)
    bb_lookback = Column(Integer, default=10)
    max_bounces = Column(Integer, default=2)
    min_atr_pct = Column(Float, default=0.3)
    max_bos_dist_atr = Column(Float, default=0.5)
    use_cooldown = Column(Boolean, default=True)
    cooldown_bars = Column(Integer, default=6)
    risk_pct = Column(Float, default=1.0)
    tp1_pct = Column(Integer, default=40)
    tp2_pct = Column(Integer, default=30)
    tp3_pct = Column(Integer, default=30)
    use_breakeven = Column(Boolean, default=True)
    use_trail = Column(Boolean, default=False)
    trailing_offset = Column(Float, default=0.25)
    is_active = Column(Boolean, default=True)
    created_at = Column(DateTime(timezone=True), server_default=func.now())
    updated_at = Column(DateTime(timezone=True), onupdate=func.now())

    __table_args__ = (
        {'sqlite_autoincrement': True}
    )


